// Turns KiCad's BOM and position CSVs into JLCPCB-style assembly files, writes the fab notes and
// zips the Gerbers. Run from the repo root after the kicad-cli exports (see README, "Fabrication"):
//   node tools/fab-package.js [output dir, default: output/fab]
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = process.argv[2] || "output/fab";
const NAME = "SolarChargeModule_v1.0";

// Manufacturer part numbers for the parts that need a specific one; generic passives are left to
// the assembler's basic-parts library. LCSC numbers only where verified (KiCad lib description).
const MPN = {
  U1: "CN3791 (Consonance)",
  U2: "INA219AIDR (TI)",
  Q1: "AO3401A (Alpha & Omega)",
  D2: "SS34",
  D5: "1N5819WS", D6: "1N5819WS", D7: "1N5819WS", D8: "1N5819WS",
  L1: "SRN6045TA-220M (Bourns)",
  SW3: "JS202011CQN (C&K)",
  J1: "53047-0210 (Molex)", J2: "53047-0210 (Molex)", J3: "53047-0210 (Molex)", J4: "53047-0210 (Molex)",
  J5: "53047-0210 (Molex)", J6: "53047-0210 (Molex)", J7: "53047-0210 (Molex)", J8: "53047-0210 (Molex)",
  J9: "53047-0410 (Molex)",
};
const LCSC = { D5: "C191023", D6: "C191023", D7: "C191023", D8: "C191023" };

function parseCsv(text) {
  return text.trim().split(/\r?\n/).map((line) => [...line.matchAll(/"([^"]*)"|([^,]+)/g)].map((m) => m[1] ?? m[2]));
}
const q = (v) => `"${String(v).replace(/"/g, '""')}"`;

// BOM: Comment, Designator, Footprint, LCSC Part #, Manufacturer Part
const [, ...bom] = parseCsv(fs.readFileSync(path.join(OUT, "bom-kicad.csv"), "utf8"));
const bomOut = [["Comment", "Designator", "Footprint", "LCSC Part #", "Manufacturer Part", "Qty"].map(q).join(",")];
for (const [value, refs, footprint, qty] of bom) {
  const first = refs.split(",")[0];
  bomOut.push([value, refs, footprint.split(":")[1], LCSC[first] || "", MPN[first] || "", qty].map(q).join(","));
}
fs.writeFileSync(path.join(OUT, `${NAME}_BOM.csv`), bomOut.join("\n") + "\n");

// CPL: Designator, Mid X, Mid Y, Layer, Rotation (same absolute coordinates as the Gerbers)
const [, ...pos] = parseCsv(fs.readFileSync(path.join(OUT, "pos-kicad.csv"), "utf8"));
const cplOut = [["Designator", "Val", "Package", "Mid X", "Mid Y", "Rotation", "Layer"].map(q).join(",")];
for (const [ref, val, pkg, x, y, rot, side] of pos) {
  if (ref.startsWith("H")) continue;  // mounting holes are not placed parts
  cplOut.push([ref, val, pkg, `${(+x).toFixed(4)}mm`, `${(+y).toFixed(4)}mm`, (+rot).toFixed(1), side === "top" ? "Top" : "Bottom"].map(q).join(","));
}
fs.writeFileSync(path.join(OUT, `${NAME}_CPL.csv`), cplOut.join("\n") + "\n");

// Order notes: the settings to pick on the board house's form, and assembly cautions.
fs.writeFileSync(path.join(OUT, "FAB_NOTES.txt"), `Solar Charge Module v1.0 (JaisorGadgets, Oct. 2026) - fabrication notes

Upload: ${NAME}_gerbers.zip (Gerber X2 + Excellon drill, generated by KiCad 10.0.7)

PCB order settings
  Layers:            2
  Size:              56.5 x 29.0 mm (2 mm 45-degree corner chamfers)
  Material:          FR-4, 1.6 mm
  Copper weight:     1 oz outer
  Min track / space: 0.25 mm / 0.2 mm
  Vias:              0.6 mm / 0.3 mm drill and 0.8 mm / 0.4 mm drill, tented
  Plated holes:      0.5 mm (Micro JST 1.25 / PicoBlade headers), 0.9 mm (slide switch SW3)
  Non-plated holes:  4 x 3.2 mm (M3 mounting), in NPTH.drl
  Solder mask:       both sides (any colour)
  Silkscreen:        both sides (back carries the module ID, I2C pin names, SW3 label)
  Surface finish:    HASL lead-free or ENIG
  Panelisation:      none; no castellations, no edge plating, no impedance control

Assembly (optional): top side only
  BOM: ${NAME}_BOM.csv   Placement: ${NAME}_CPL.csv (same coordinates as the Gerbers)
  - LCSC part numbers are filled in only where verified (D5-D8). Pick the rest in the
    assembler's part search; the Manufacturer Part column names the specific parts.
  - Check part rotation and polarity in the assembler's preview before ordering, especially
    U1 (CN3791), U2 (INA219), Q1, D2, D5-D8 and the LEDs D3 (green) / D4 (red).
  - Through-hole parts: J1-J9 (Molex 53047 PicoBlade headers) and SW3 (C&K JS202011CQN).
    Hand-solder them, or order through-hole assembly.
  - H1-H4 are mounting holes, not parts (left out of the BOM and placement files).
`);

// Gerber + drill zip: the file the board house uploads.
const zip = path.join(OUT, `${NAME}_gerbers.zip`);
fs.rmSync(zip, { force: true });
execFileSync("C:/Program Files/KiCad/10.0/bin/python.exe", ["-c",
  `import zipfile, pathlib, sys
src, dst = pathlib.Path(sys.argv[1]), sys.argv[2]
with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
    for f in sorted(src.iterdir()):
        z.write(f, f.name)`, path.join(OUT, "gerbers"), zip]);
console.log(`wrote ${NAME}_BOM.csv (${bomOut.length - 1} lines), ${NAME}_CPL.csv (${cplOut.length - 1} parts), ${NAME}_gerbers.zip`);
